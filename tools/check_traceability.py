#!/usr/bin/env python3
"""Requirement-to-test traceability tool.

Requirements live in docs/REQUIREMENTS.md as headings of the form

    ### REQ-KIN-001: Short title

Tests declare which requirements they verify with a tag comment on the line(s)
immediately before the GoogleTest macro:

    // @verifies REQ-KIN-001
    TEST(Suite, Name) { ... }

Usage
    python tools/check_traceability.py --check   # exit 1 on any gap (used by CTest and CI)
    python tools/check_traceability.py --write   # regenerate docs/TRACEABILITY.md

--check fails if
  * a requirement has no verifying test,
  * a test references a requirement that does not exist, or
  * docs/TRACEABILITY.md is out of date with respect to the sources.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS = ROOT / "docs" / "REQUIREMENTS.md"
TRACEABILITY = ROOT / "docs" / "TRACEABILITY.md"
TEST_DIR = ROOT / "tests"

REQ_HEADING = re.compile(r"^###\s+(REQ-[A-Z]+-\d{3})\s*:\s*(.+?)\s*$")
VERIFIES = re.compile(r"@verifies\s+((?:REQ-[A-Z]+-\d{3}[\s,]*)+)")
REQ_ID = re.compile(r"REQ-[A-Z]+-\d{3}")
TEST_MACRO = re.compile(r"^\s*(TEST|TEST_F|TEST_P)\s*\(\s*(\w+)\s*,\s*(\w+)\s*\)")


def load_requirements() -> dict[str, str]:
    reqs: dict[str, str] = {}
    for line in REQUIREMENTS.read_text(encoding="utf-8").splitlines():
        m = REQ_HEADING.match(line)
        if m:
            if m.group(1) in reqs:
                sys.exit(f"Duplicate requirement ID {m.group(1)} in {REQUIREMENTS.name}")
            reqs[m.group(1)] = m.group(2)
    return reqs


def load_test_links() -> dict[str, list[str]]:
    """Map requirement ID -> sorted list of 'file: Suite.Name'."""
    links: dict[str, set[str]] = defaultdict(set)
    for path in sorted(TEST_DIR.rglob("*.cpp")):
        pending: list[str] = []
        for line in path.read_text(encoding="utf-8").splitlines():
            tag = VERIFIES.search(line)
            if tag:
                pending.extend(REQ_ID.findall(tag.group(1)))
                continue
            macro = TEST_MACRO.match(line)
            if macro:
                for req in pending:
                    links[req].add(f"`{path.name}`: {macro.group(2)}.{macro.group(3)}")
                pending = []
            elif line.strip() and not line.strip().startswith("//"):
                pending = []  # tag must sit directly above the test macro
    return {k: sorted(v) for k, v in links.items()}


def render(reqs: dict[str, str], links: dict[str, list[str]]) -> str:
    out = [
        "# Traceability Matrix",
        "",
        "<!-- GENERATED by tools/check_traceability.py --write. Do not edit by hand. -->",
        "",
        "Every requirement in [REQUIREMENTS.md](REQUIREMENTS.md) maps to at least one automated test.",
        "Tests declare coverage with a `// @verifies REQ-...` comment directly above the `TEST(...)` macro.",
        "The CTest target `traceability_check` (run in CI) fails if any requirement is uncovered,",
        "if a test cites an unknown requirement, or if this file is stale.",
        "",
        f"**{len(reqs)} requirements, {sum(1 for r in reqs if links.get(r))} covered.**",
        "",
        "| Requirement | Title | Verified by |",
        "|---|---|---|",
    ]
    for req, title in reqs.items():
        tests = links.get(req, [])
        cell = "<br>".join(tests) if tests else "**NOT COVERED**"
        out.append(f"| {req} | {title} | {cell} |")
    out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="fail on gaps or a stale matrix")
    mode.add_argument("--write", action="store_true", help="regenerate docs/TRACEABILITY.md")
    args = parser.parse_args()

    reqs = load_requirements()
    links = load_test_links()
    errors: list[str] = []

    if not reqs:
        errors.append(f"No requirements found in {REQUIREMENTS}")
    for req in reqs:
        if not links.get(req):
            errors.append(f"{req} ({reqs[req]}) has no verifying test")
    for req in sorted(set(links) - set(reqs)):
        errors.append(f"Tests reference unknown requirement {req}: {', '.join(links[req])}")

    text = render(reqs, links)
    if args.write:
        TRACEABILITY.write_text(text, encoding="utf-8", newline="\n")
        print(f"Wrote {TRACEABILITY.relative_to(ROOT)}")
    elif not TRACEABILITY.exists() or TRACEABILITY.read_text(encoding="utf-8") != text:
        errors.append("docs/TRACEABILITY.md is stale: run `python tools/check_traceability.py --write`")

    for e in errors:
        print(f"TRACEABILITY ERROR: {e}", file=sys.stderr)
    if not errors:
        covered = sum(1 for r in reqs if links.get(r))
        print(f"Traceability OK: {covered}/{len(reqs)} requirements covered by tests.")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
